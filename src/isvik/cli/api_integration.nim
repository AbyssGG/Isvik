## 成品客户端接入参数与「启动前确保有可用 Key」。
##
## 这个模块存在的唯一理由是**三条启动路径共用同一份行为**:
##
## ```text
## isvik api serve                  强制鉴权
## isvik serve --require-api-key    等价的旧入口
## 工作台 -serve                     转发给上面第一条
## ```
##
## 之前 URL 拼装只在 `cli/cmd_api` 里,而自动补 Key 要发生在 `cli/cmd_serve`
## (那才是所有启动路径的汇合点)。`cmd_api` 已经 import `cmd_serve`,反向
## import 会成环 —— 于是把两者都下沉到这里,而不是复制一份到 cmd_serve。

import std/[json, strutils]

import isvik/config/api_keys
import isvik/config/paths
import isvik/cli/context
import isvik/cli/output

const AutoServeKeyName* = "auto-serve"
  ## 自动生成的 Key 用固定的 ASCII 名字,**不**用本地化文本:名字会写进
  ## api_keys.json,随界面语言变化会让同一台机器上的记录看起来来源不同。

proc integrationHost*(host: string): string =
  ## 监听 0.0.0.0 / :: 时,给本机客户端一个可连接的回环地址。
  var normalized = host.strip()
  if normalized.len == 0 or normalized == "0.0.0.0" or normalized == "::":
    normalized = "127.0.0.1"
  if normalized.startsWith("[") and normalized.endsWith("]"):
    return normalized
  if normalized.contains(':'):
    return "[" & normalized & "]"
  normalized

proc apiIntegrationUrls*(host: string, port: int):
    tuple[openaiBase, openaiFull, anthropicBase, anthropicFull: string] =
  let origin = "http://" & integrationHost(host) & ":" & $port
  result.openaiBase = origin & "/v1"
  result.openaiFull = origin & "/v1/chat/completions"
  result.anthropicBase = origin
  result.anthropicFull = origin & "/v1/messages"

proc apiIntegrationUrls*(ctx: CliContext):
    tuple[openaiBase, openaiFull, anthropicBase, anthropicFull: string] =
  apiIntegrationUrls(ctx.settings.server.host, ctx.settings.server.port)

proc apiIntegrationJson*(host: string, port: int): JsonNode =
  let urls = apiIntegrationUrls(host, port)
  var openai = newJObject()
  openai["baseUrl"] = %urls.openaiBase
  openai["fullUrl"] = %urls.openaiFull
  var anthropic = newJObject()
  anthropic["baseUrl"] = %urls.anthropicBase
  anthropic["fullUrl"] = %urls.anthropicFull
  result = newJObject()
  result["openai"] = openai
  result["anthropic"] = anthropic

proc apiIntegrationJson*(ctx: CliContext): JsonNode =
  apiIntegrationJson(ctx.settings.server.host, ctx.settings.server.port)

proc printApiIntegration*(ctx: CliContext, host: string, port: int) =
  let urls = apiIntegrationUrls(host, port)
  # 这四个标签里最长的 `Anthropic Base URL` 正好 18 个字符,用 kvLine 的默认
  # 宽度会让标签与 URL 直接粘连成 `Anthropic Base URLhttp://...`。URL 是要
  # 被复制到客户端的内容,粘连会让人连不上却看不出原因,所以显式加宽。
  const UrlLabelWidth = 21
  echo ctx.t("api.integration.title")
  echo kvLine(ctx.t("api.integration.openai"), urls.openaiBase, UrlLabelWidth)
  echo kvLine(ctx.t("api.integration.openaiFull"), urls.openaiFull,
              UrlLabelWidth)
  echo kvLine(ctx.t("api.integration.anthropic"), urls.anthropicBase,
              UrlLabelWidth)
  echo kvLine(ctx.t("api.integration.anthropicFull"), urls.anthropicFull,
              UrlLabelWidth)
  echo "  " & ctx.t("api.integration.fullUrl")

proc printApiIntegration*(ctx: CliContext) =
  printApiIntegration(ctx, ctx.settings.server.host, ctx.settings.server.port)

proc ensureServeApiKey*(ctx: CliContext, host: string, port: int,
                        requireApiKey, autoKey: bool) =
  ## 启动强制鉴权的服务前,保证至少有一个可用 Key。
  ##
  ## 为什么默认自动补:`api serve` 强制鉴权,而一个 active Key 都没有时服务能
  ## 起来却**所有请求都是 401** —— 那是一个能启动但完全不可用的状态,让用户
  ## 自己发现并回头执行 create 是多余的一步。
  ##
  ## 三条边界:
  ##
  ## - 只在**强制鉴权**时补。无鉴权模式不需要 Key,凭空写一个凭据文件是副作用。
  ## - 只在**没有任何 active Key** 时补。已经有可用 Key 就不动,否则每次启动都
  ##   往文件里堆一个,用户很快分不清哪个在用。
  ## - `--no-auto-key` 可以关掉。关掉后若确实没有 Key,**必须警告** ——
  ##   静默启动一个全 401 的服务比自动补 Key 糟糕得多。
  if not requireApiKey:
    return

  let keyFile = ctx.paths.apiKeysFile
  if activeApiKeyCount(keyFile) > 0:
    return

  if not autoKey:
    echo ctx.t("serve.autoKey.disabled")
    return

  ctx.paths.ensureDirectories()
  let created = createApiKey(keyFile, AutoServeKeyName)

  if ctx.isJson:
    # JSON 模式下服务日志本身不是 JSON,但这条是**凭据**,必须能被脚本取到,
    # 而不是只印在人读的文本里。
    var output = publicApiKeyJson(created.record)
    output["apiKey"] = %created.secret
    output["autoGenerated"] = %true
    output["integration"] = apiIntegrationJson(host, port)
    emitJson(output)
    return

  echo ""
  echo ctx.t("serve.autoKey.created")
  echo kvLine(ctx.t("api.key.id"), created.record.id)
  echo kvLine(ctx.t("api.key.name"), created.record.name)
  echo kvLine(ctx.t("api.key.secret"), created.secret)
  echo ""
  echo "  " & ctx.t("serve.autoKey.hint")
  echo ""
  printApiIntegration(ctx, host, port)
  echo ""
